namespace Magidesk.Domain.Enumerations;

/// <summary>
/// Represents the type of equipment used in the billiard club.
/// </summary>
public enum EquipmentType
{
    /// <summary>
    /// Pool cue stick.
    /// </summary>
    Cue,

    /// <summary>
    /// Set of billiard balls.
    /// </summary>
    BallSet,

    /// <summary>
    /// Triangle rack for organizing balls.
    /// </summary>
    Rack,

    /// <summary>
    /// Chalk for cue tips.
    /// </summary>
    Chalk,

    /// <summary>
    /// Bridge stick for difficult shots.
    /// </summary>
    BridgeStick,

    /// <summary>
    /// Cover to protect the table when not in use.
    /// </summary>
    TableCover,

    /// <summary>
    /// Lighting equipment for the table.
    /// </summary>
    Lighting,

    /// <summary>
    /// Other miscellaneous equipment.
    /// </summary>
    Other
}